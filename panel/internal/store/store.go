// UpdateNodeOperatorFields updates only operator-owned columns. An address edit
// adjusts status atomically; metrics, versions and config hashes stay untouched.
func (s *Store) UpdateNodeOperatorFields(id string, update NodeOperatorUpdate) error {
	if id == "" {
		return fmt.Errorf("必须提供节点 ID")
	}

	sets := make([]string, 0, 12)
	args := make([]any, 0, 14)
	add := func(column string, value any) {
		sets = append(sets, column+" = ?")
		args = append(args, value)
	}

	if update.Name != nil {
		add("name", *update.Name)
	}
	if update.Address != nil {
		add("address", *update.Address)
		sets = append(sets, `status = CASE
			WHEN ? = '' THEN 'pending'
			WHEN status = 'pending' THEN 'unknown'
			ELSE status
		END`)
		args = append(args, *update.Address)
	}
	if update.GRPCPort != nil {
		add("grpc_port", *update.GRPCPort)
	}
	if update.Token != nil {
		add("token", *update.Token)
	}
	if update.Labels != nil {
		labels := append([]string{}, (*update.Labels)...)
		labelsJSON, err := marshalJSON(labels)
		if err != nil {
			return fmt.Errorf("编码标签失败：%w", err)
		}
		add("labels_json", labelsJSON)
	}
	if update.PublicAddress != nil {
		add("public_address", *update.PublicAddress)
	}
	if update.PortMappings != nil {
		mappingsJSON, err := marshalJSON(NormalizePortMappings(*update.PortMappings))
		if err != nil {
			return fmt.Errorf("编码端口映射失败：%w", err)
		}
		add("port_mappings_json", mappingsJSON)
	}
	if update.EgressInterface != nil {
		add("egress_interface", *update.EgressInterface)
	}
	if update.DNS != nil {
		cfg := *update.DNS
		dnsJSON, err := encodeNodeDNS(&cfg)
		if err != nil {
			return err
		}
		add("dns_json", dnsJSON)
	}
	if update.DDNSEnabled != nil {
		add("ddns_enabled", boolToInt(*update.DDNSEnabled))
	}
	if update.ControlMode != nil {
		mode := strings.TrimSpace(*update.ControlMode)
		if err := validateControlMode(mode); err != nil {
			return err
		}
		add("control_mode", mode)
	}
	if update.DesiredRuntime != nil {
		state := strings.TrimSpace(*update.DesiredRuntime)
		if err := validateDesiredRuntime(state); err != nil {
			return err
		}
		add("desired_runtime", state)
	}

	add("updated_at_unix", nowUnix())
	args = append(args, id)
	res, err := s.db.Exec(`UPDATE nodes SET `+strings.Join(sets, ", ")+` WHERE id = ?`, args...)
	if err != nil {
		return fmt.Errorf("更新节点管理字段失败：%w", err)
	}
	rows, _ := res.RowsAffected()
	if rows == 0 {
		return fmt.Errorf("节点不存在：%s", id)
	}
	return nil
}

// ApplyNodeReport updates only report/live columns. Older collected_at_unix samples are dropped.
func (s *Store) ApplyNodeReport(nodeID string, report NodeReport) (bool, error) {
	if nodeID == "" {
		return false, fmt.Errorf("必须提供节点 ID")
	}
	if report.CPUPercent < 0 || report.CPUPercent > 100 {
		return false, fmt.Errorf("CPU 使用率无效")
	}
	if report.Connections < 0 || report.UplinkBytes < 0 || report.DownlinkBytes < 0 || report.MemoryRSSBytes < 0 {
		return false, fmt.Errorf("上报指标不能为负数")
	}
	collected := report.CollectedAtUnix
	if collected < 0 {
		return false, fmt.Errorf("上报时间戳无效")
	}
	now := nowUnix()
	if collected == 0 {
		collected = now
	}
	if collected > now+300 {
		return false, fmt.Errorf("上报时间戳超出允许范围")
	}

	capsJSON := "[]"
	updateCaps := 0
	if report.HasCapabilities {
		updateCaps = 1
		if report.Capabilities == nil {
			report.Capabilities = []string{}
		}
		encoded, err := marshalJSON(report.Capabilities)
		if err != nil {
			return false, fmt.Errorf("编码节点能力失败：%w", err)
		}
		capsJSON = encoded
	}
	updateMetrics := 0
	if report.HasMetrics {
		updateMetrics = 1
	}
	updateHash := 0
	if report.ConfigHash != "" {
		updateHash = 1
	}
	updateAgent := 0
	if report.AgentVersion != "" {
		updateAgent = 1
	}
	updateSingbox := 0
	if report.SingboxVersion != "" {
		updateSingbox = 1
	}
	updateCore := 0
	if report.CoreVersion != "" {
		updateCore = 1
	}
	updateCoreCommit := 0
	if report.CoreCommit != "" {
		updateCoreCommit = 1
	}
	updateClientType := 0
	if report.ClientType != "" {
		updateClientType = 1
	}
	updateClientVersion := 0
	if report.ClientVersion != "" {
		updateClientVersion = 1
	}
	updateLuci := 0
	if report.LuciVersion != "" {
		updateLuci = 1
	}

	res, err := s.db.Exec(`
		UPDATE nodes SET
			status = CASE WHEN ? != '' THEN ? ELSE status END,
			last_seen_unix = ?,
			runtime_state = CASE WHEN ? != '' THEN ? ELSE runtime_state END,
			config_hash = CASE WHEN ? != 0 THEN ? ELSE config_hash END,
			last_error = ?,
			connections = CASE WHEN ? != 0 THEN ? ELSE connections END,
			uplink_bytes = CASE WHEN ? != 0 THEN ? ELSE uplink_bytes END,
			downlink_bytes = CASE WHEN ? != 0 THEN ? ELSE downlink_bytes END,
			cpu_percent = CASE WHEN ? != 0 THEN ? ELSE cpu_percent END,
			memory_rss_bytes = CASE WHEN ? != 0 THEN ? ELSE memory_rss_bytes END,
			metrics_at_unix = CASE WHEN ? != 0 THEN ? ELSE metrics_at_unix END,
			capabilities_json = CASE WHEN ? != 0 THEN ? ELSE capabilities_json END,
			agent_version = CASE WHEN ? != 0 THEN ? ELSE agent_version END,
			singbox_version = CASE WHEN ? != 0 THEN ? ELSE singbox_version END,
			core_version = CASE WHEN ? != 0 THEN ? ELSE core_version END,
			core_commit = CASE WHEN ? != 0 THEN ? ELSE core_commit END,
			client_type = CASE WHEN ? != 0 THEN ? ELSE client_type END,
			client_version = CASE WHEN ? != 0 THEN ? ELSE client_version END,
			luci_version = CASE WHEN ? != 0 THEN ? ELSE luci_version END,
			uplink_last_seen_unix = ?,
			updated_at_unix = ?
		WHERE id = ? AND uplink_last_seen_unix <= ?`,
		report.Status, report.Status,
		collected,
		report.RuntimeState, report.RuntimeState,
		updateHash, report.ConfigHash,
		report.LastError,
		updateMetrics, report.Connections,
		updateMetrics, report.UplinkBytes,
		updateMetrics, report.DownlinkBytes,
		updateMetrics, report.CPUPercent,
		updateMetrics, report.MemoryRSSBytes,
		updateMetrics, collected,
		updateCaps, capsJSON,
		updateAgent, report.AgentVersion,
		updateSingbox, report.SingboxVersion,
		updateCore, report.CoreVersion,
		updateCoreCommit, report.CoreCommit,
		updateClientType, report.ClientType,
		updateClientVersion, report.ClientVersion,
		updateLuci, report.LuciVersion,
		collected, now,
		nodeID, collected,
	)
	if err != nil {
		return false, fmt.Errorf("写入节点上报失败：%w", err)
	}
	rows, _ := res.RowsAffected()
	if rows == 0 {
		var exists int
		if err := s.db.QueryRow(`SELECT COUNT(1) FROM nodes WHERE id = ?`, nodeID).Scan(&exists); err != nil {
			return false, fmt.Errorf("检查节点失败：%w", err)
		}
		if exists == 0 {
			return false, fmt.Errorf("节点不存在：%s", nodeID)
		}
		return false, nil
	}
	return true, nil
}

// MarkUplinkUnreachable sets status only when the newest accepted report is still older
// than cutoffUnix, so a concurrent ApplyNodeReport cannot be overwritten.
func (s *Store) MarkUplinkUnreachable(nodeID, lastError string, cutoffUnix int64) error {
	if nodeID == "" {
		return fmt.Errorf("必须提供节点 ID")
	}
	_, err := s.db.Exec(`
		UPDATE nodes SET status = 'unreachable', last_error = ?, updated_at_unix = ?
		WHERE id = ? AND control_mode = ? AND uplink_last_seen_unix > 0 AND uplink_last_seen_unix < ?`,
		lastError, nowUnix(), nodeID, ControlModeUplink, cutoffUnix,
	)
	if err != nil {
		return fmt.Errorf("标记 uplink 节点不可达失败：%w", err)
	}
	return nil
}

func (s *Store) DeleteNode(id string) error {
	tx, err := s.db.Begin()
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback() }()

	rows, err := tx.Query(`
		SELECT DISTINCT c.name
		FROM proxy_chain_hops h
		JOIN proxy_chains c ON c.id = h.chain_id
		WHERE h.node_id = ?
		ORDER BY c.name`, id)
	if err != nil {
		return fmt.Errorf("检查节点的代理链引用失败：%w", err)
	}
	var chainNames []string
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			_ = rows.Close()
			return fmt.Errorf("读取节点的代理链引用失败：%w", err)
		}
		chainNames = append(chainNames, name)
	}
	if err := rows.Close(); err != nil {
		return fmt.Errorf("关闭代理链引用查询失败：%w", err)
	}
	if len(chainNames) > 0 {
		return fmt.Errorf("节点仍被代理链引用：%s；请先替换对应跳点或删除代理链", strings.Join(chainNames, "、"))
	}

	var runningAutomation int
	if err := tx.QueryRow(`
		SELECT COUNT(*) FROM automation_jobs
		WHERE state = 'running' AND (
			(target_type = 'managed_domain' AND target_id IN (
				SELECT id FROM managed_domains WHERE node_id = ?
			)) OR
			(target_type = 'protocol_certificate' AND target_id IN (
				SELECT id FROM protocol_certificates WHERE node_id = ?
			))
		)`, id, id,
	).Scan(&runningAutomation); err != nil {
		return fmt.Errorf("检查节点自动化任务失败：%w", err)
	}
	if runningAutomation > 0 {
		return fmt.Errorf("节点有 %d 个正在执行的 DNS/证书任务，请等待任务结束后再删除", runningAutomation)
	}
	if _, err := tx.Exec(`
		DELETE FROM automation_jobs
		WHERE target_type = 'protocol_certificate'
			AND target_id IN (SELECT id FROM protocol_certificates WHERE node_id = ?)`,
		id,
	); err != nil {
		return fmt.Errorf("取消节点协议证书任务失败：%w", err)
	}
	if _, err := tx.Exec(`
		DELETE FROM automation_jobs
		WHERE target_type = 'managed_domain'
			AND target_id IN (SELECT id FROM managed_domains WHERE node_id = ?)`,
		id,
	); err != nil {
		return fmt.Errorf("取消节点 DNS 任务失败：%w", err)
	}
	if _, err := tx.Exec(`DELETE FROM node_inbounds WHERE node_id = ?`, id); err != nil {
		return fmt.Errorf("删除节点入站关联失败：%w", err)
	}
	res, err := tx.Exec(`DELETE FROM nodes WHERE id = ?`, id)
	if err != nil {
		return fmt.Errorf("删除节点失败：%w", err)
	}
	affected, _ := res.RowsAffected()
	if affected == 0 {
		return fmt.Errorf("节点不存在：%s", id)
	}
	return tx.Commit()
}

func scanNode(row interface {
	Scan(dest ...any) error
}) (*Node, error) {
	var n Node
	var labelsJSON string
	var mappingsJSON string
	var capabilitiesJSON string
	var ddnsEnabled int
	var dnsJSON string
	err := row.Scan(
		&n.ID, &n.Name, &n.Address, &n.GRPCPort, &n.Token, &labelsJSON, &n.PKICABundlePEM,
		&n.PKICertSerial, &n.PKINotAfter,
		&n.Status, &n.LastSeenUnix, &n.ConfigHash,
		&n.RuntimeState, &n.AgentVersion, &n.SingboxVersion,
		&n.Connections, &n.UplinkBytes, &n.DownlinkBytes, &n.CPUPercent, &n.MemoryRSSBytes,
		&n.MetricsAtUnix, &n.LastError, &n.EgressInterface, &n.PublicAddress, &mappingsJSON, &capabilitiesJSON,
		&ddnsEnabled, &n.ControlMode, &n.DesiredRuntime, &n.UplinkLastSeenUnix, &n.CreatedAtUnix, &n.UpdatedAtUnix,
		&n.CoreVersion, &n.CoreCommit, &n.ClientType, &n.ClientVersion, &n.LuciVersion,
		&dnsJSON,
	)
	if err != nil {
		return nil, err
	}
	n.DDNSEnabled = ddnsEnabled != 0
	if n.ControlMode == "" {
		n.ControlMode = ControlModePush
	}
	if n.DesiredRuntime == "" {
		n.DesiredRuntime = DesiredRuntimeRunning
	}
	n.Labels = []string{}
	if err := unmarshalJSON(labelsJSON, &n.Labels); err != nil {
		return nil, fmt.Errorf("解析标签失败：%w", err)
	}
	n.PortMappings = []PortMapping{}
	if err := unmarshalJSON(mappingsJSON, &n.PortMappings); err != nil {
		return nil, fmt.Errorf("解析端口映射失败：%w", err)
	}
	n.PortMappings = NormalizePortMappings(n.PortMappings)
	n.Capabilities = []string{}
	if err := unmarshalJSON(capabilitiesJSON, &n.Capabilities); err != nil {
		return nil, fmt.Errorf("解析节点能力失败：%w", err)
	}
	n.DNS, err = nodedns.Parse(dnsJSON)
	if err != nil {
		return nil, err
	}
	return &n, nil
}

