// Store is a SQLite-backed persistence layer for the panel.
type Store struct {
	db *sql.DB
	// mu serializes the read-modify-write command-queue transitions
	// (lease/complete) so at-least-once delivery stays consistent on the
	// single-writer SQLite connection.
	mu sync.Mutex
}

// Open opens (or creates) a SQLite database at path and ensures schema + defaults.
func Open(path string) (*Store, error) {
	db, err := sql.Open("sqlite", path)
	if err != nil {
		return nil, fmt.Errorf("打开 SQLite 数据库失败：%w", err)
	}
	// Single-writer is typical for panel; keep it simple and reliable.
	db.SetMaxOpenConns(1)
	if _, err := db.Exec(`PRAGMA foreign_keys = ON`); err != nil {
		_ = db.Close()
		return nil, fmt.Errorf("启用 SQLite 外键失败：%w", err)
	}

	s := &Store{db: db}
	if err := s.migrate(); err != nil {
		_ = db.Close()
		return nil, err
	}
	if err := s.repairInvalidShadowsocks2022Passwords(); err != nil {
		_ = db.Close()
		return nil, err
	}
	if err := s.ensureDefaultSettings(); err != nil {
		_ = db.Close()
		return nil, err
	}
	return s, nil
}

// repairInvalidShadowsocks2022Passwords migrates credentials generated by
// versions up to v0.9.0. Those versions used a generic URL-safe password for
// every Shadowsocks method, while SS2022 requires a standard Base64 PSK with a
// method-specific minimum length.
func (s *Store) repairInvalidShadowsocks2022Passwords() error {
	rows, err := s.db.Query(`SELECT id, params_json FROM inbounds WHERE protocol = 'shadowsocks'`)
	if err != nil {
		return fmt.Errorf("查询需要修复 PSK 的 Shadowsocks 入站失败：%w", err)
	}
	type record struct {
		id     string
		params map[string]any
	}
	var repairs []record
	for rows.Next() {
		var id, paramsJSON string
		if err := rows.Scan(&id, &paramsJSON); err != nil {
			_ = rows.Close()
			return fmt.Errorf("读取待修复的 Shadowsocks 入站失败：%w", err)
		}
		params := map[string]any{}
		if err := unmarshalJSON(paramsJSON, &params); err != nil {
			_ = rows.Close()
			return fmt.Errorf("解析 Shadowsocks 入站 %s 以修复 PSK 失败：%w", id, err)
		}
		changed, err := inboundfill.RepairShadowsocks2022Password(params)
		if err != nil {
			_ = rows.Close()
			return fmt.Errorf("修复 Shadowsocks 入站 %s 的 PSK 失败：%w", id, err)
		}
		if changed {
			repairs = append(repairs, record{id: id, params: params})
		}
	}
	if err := rows.Err(); err != nil {
		_ = rows.Close()
		return fmt.Errorf("查询需要修复 PSK 的 Shadowsocks 入站失败：%w", err)
	}
	if err := rows.Close(); err != nil {
		return err
	}
	for _, repair := range repairs {
		paramsJSON, err := marshalJSON(repair.params)
		if err != nil {
			return fmt.Errorf("编码已修复的 Shadowsocks 入站 %s 失败：%w", repair.id, err)
		}
		if _, err := s.db.Exec(
			`UPDATE inbounds SET params_json = ?, updated_at_unix = ? WHERE id = ?`,
			paramsJSON, nowUnix(), repair.id,
		); err != nil {
			return fmt.Errorf("保存已修复的 Shadowsocks 入站 %s PSK 失败：%w", repair.id, err)
		}
	}
	return nil
}

// Close closes the underlying database.
func (s *Store) Close() error {
	if s == nil || s.db == nil {
		return nil
	}
	return s.db.Close()
}

